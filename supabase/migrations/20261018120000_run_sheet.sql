-- Run sheet: trucks, kitchen / timing defaults, per-event truck assignment and
-- timing, and live status from the crew (leaving, arrived, setup done, done).
-- Crew links can now be limited to one truck, and crews can read the
-- contract (without prices). Events get an optional service end time
-- (service_data.event_end_time), shown on contracts.
--
-- Additive only: new tables, one new nullable column on crew_links, and
-- replaced functions. Existing customer data is not modified.

-- ---------------------------------------------------------------------------
-- 1. Trucks / crews
-- ---------------------------------------------------------------------------
create table if not exists public.trucks (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 40),
  color text not null default 'blue' check (color in ('blue', 'green', 'amber', 'purple', 'rose', 'slate')),
  created_at timestamptz not null default now()
);
create index if not exists trucks_user_id_idx on public.trucks (user_id);

alter table public.trucks enable row level security;
drop policy if exists "Owners manage their trucks" on public.trucks;
create policy "Owners manage their trucks" on public.trucks
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- ---------------------------------------------------------------------------
-- 2. Where trucks leave from and default timings
-- ---------------------------------------------------------------------------
create table if not exists public.ops_settings (
  user_id uuid primary key default auth.uid() references auth.users(id) on delete cascade,
  kitchen_address text check (kitchen_address is null or length(kitchen_address) <= 200),
  setup_minutes integer not null default 60 check (setup_minutes between 0 and 600),
  drive_minutes integer not null default 30 check (drive_minutes between 0 and 600),
  -- used when an event has no end time
  service_minutes integer not null default 240 check (service_minutes between 0 and 1440),
  -- packing up after service ends, before the truck can leave
  teardown_minutes integer not null default 30 check (teardown_minutes between 0 and 600),
  updated_at timestamptz not null default now()
);

alter table public.ops_settings enable row level security;
drop policy if exists "Owners manage their ops settings" on public.ops_settings;
create policy "Owners manage their ops settings" on public.ops_settings
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- ---------------------------------------------------------------------------
-- 3. Per-event run info: truck, timing changes, live status
--    setup_minutes:    time needed on site before service starts
--    teardown_minutes: packing up after service ends
--    drive_minutes:    drive from the previous stop (or the kitchen)
--    null = use the defaults from ops_settings
-- ---------------------------------------------------------------------------
create table if not exists public.event_runs (
  customer_id bigint primary key references public.customers(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  truck_id bigint references public.trucks(id) on delete set null,
  setup_minutes integer check (setup_minutes is null or setup_minutes between 0 and 600),
  teardown_minutes integer check (teardown_minutes is null or teardown_minutes between 0 and 600),
  drive_minutes integer check (drive_minutes is null or drive_minutes between 0 and 600),
  departed_at timestamptz,
  arrived_at timestamptz,
  setup_done_at timestamptz,
  finished_at timestamptz,
  status_by text check (status_by is null or length(status_by) <= 60),
  updated_at timestamptz not null default now()
);
create index if not exists event_runs_user_id_idx on public.event_runs (user_id);
create index if not exists event_runs_truck_id_idx on public.event_runs (truck_id);

alter table public.event_runs enable row level security;
drop policy if exists "Owners manage their event runs" on public.event_runs;
create policy "Owners manage their event runs" on public.event_runs
  for all
  using (auth.uid() = user_id)
  with check (
    auth.uid() = user_id
    and exists (select 1 from public.customers c where c.id = customer_id and c.user_id = auth.uid())
    and (truck_id is null or exists (select 1 from public.trucks t where t.id = truck_id and t.user_id = auth.uid()))
  );

-- ---------------------------------------------------------------------------
-- 4. Crew links can be limited to one truck (null = every event that day)
-- ---------------------------------------------------------------------------
alter table public.crew_links add column if not exists truck_id bigint references public.trucks(id) on delete cascade;

-- ---------------------------------------------------------------------------
-- 5. Contracts show the service end time too
-- ---------------------------------------------------------------------------
create or replace function public.contract_public_service_data(sd jsonb)
returns jsonb
language sql
immutable
set search_path = ''
as $$
  select coalesce(jsonb_object_agg(key, value), '{}'::jsonb)
  from jsonb_each(coalesce(sd, '{}'::jsonb))
  where key in (
    'event_date', 'event_time', 'event_end_time', 'guest_count', 'price_per_head',
    'menu_entrees', 'menu_sides', 'menu_drinks', 'menu_desserts', 'menu_supplies',
    'selected_menu_items',
    'payment_plan', 'signed_by', 'signed_at', 'terms_accepted'
  )
$$;
revoke all on function public.contract_public_service_data(jsonb) from public, anon, authenticated;

-- What the crew sees of a contract: the signed copy when there is one,
-- otherwise the current details. Prices and payments are removed.
create or replace function public.crew_contract(c public.customers)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'status', case
      when c.contract_url = 'SIGNED_DIGITALLY' then 'signed'
      when c.contract_url is not null then 'file'
      else 'none' end,
    'file_url', case when c.contract_url is not null and c.contract_url <> 'SIGNED_DIGITALLY' then c.contract_url end,
    'signed_by', coalesce(c.signed_contract ->> 'signed_by', c.service_data ->> 'signed_by'),
    'signed_at', coalesce(c.signed_contract ->> 'signed_at', c.service_data ->> 'signed_at'),
    'terms_version', coalesce((c.signed_contract ->> 'terms_version')::int, 1),
    'full_name', coalesce(c.signed_contract ->> 'full_name', c.full_name),
    'address', coalesce(c.signed_contract ->> 'address', c.address),
    'city', coalesce(c.signed_contract ->> 'city', c.city),
    'job_notes', coalesce(c.signed_contract ->> 'job_notes', c.job_notes),
    'service_data', coalesce(c.signed_contract -> 'service_data', public.contract_public_service_data(c.service_data))
      - 'payment_plan' - 'price_per_head'
  )
$$;
revoke all on function public.crew_contract(public.customers) from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 6. Crew functions, now truck-aware
-- ---------------------------------------------------------------------------

-- Event belongs to the link's owner, day and (if set) truck
create or replace function public.crew_check_event(l public.crew_links, p_customer_id bigint)
returns void
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform 1
  from public.customers c
  where c.id = p_customer_id
    and c.user_id = l.user_id
    and c.status = 'sold'
    and left(c.service_data ->> 'event_date', 10) = l.day::text
    and (
      l.truck_id is null
      or exists (select 1 from public.event_runs r where r.customer_id = c.id and r.truck_id = l.truck_id)
    );
  if not found then
    raise exception 'Event not found';
  end if;
end;
$$;

create or replace function public.crew_day(p_token uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  l public.crew_links%rowtype;
  v_ids bigint[];
begin
  l := public.crew_valid_link(p_token);

  select coalesce(array_agg(c.id), '{}') into v_ids
  from public.customers c
  where c.user_id = l.user_id
    and c.status = 'sold'
    and left(c.service_data ->> 'event_date', 10) = l.day::text
    and (
      l.truck_id is null
      or exists (select 1 from public.event_runs r where r.customer_id = c.id and r.truck_id = l.truck_id)
    );

  return jsonb_build_object(
    'day', l.day,
    'business_name', public.business_name_for(l.user_id),
    'truck_id', l.truck_id,
    'events', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', c.id,
        'full_name', c.full_name,
        'phone', c.phone,
        'address', c.address,
        'city', c.city,
        'service_data', (
          select coalesce(jsonb_object_agg(key, value), '{}'::jsonb)
          from jsonb_each(coalesce(c.service_data, '{}'::jsonb))
          where key in (
            'event_date', 'event_time', 'event_end_time', 'guest_count', 'setup', 'dietary_restrictions',
            'kitchen_notes', 'timeline',
            'menu_entrees', 'menu_sides', 'menu_drinks', 'menu_desserts', 'menu_supplies',
            'selected_menu_items'
          )
        ),
        'contract', public.crew_contract(c)
      ) order by c.service_data ->> 'event_time')
      from public.customers c
      where c.id = any(v_ids)
    ), '[]'::jsonb),
    'equipment', coalesce((
      select jsonb_agg(to_jsonb(e) - 'user_id')
      from public.equipment e
      where e.user_id = l.user_id
    ), '[]'::jsonb),
    'menu_links', coalesce((
      select jsonb_agg(jsonb_build_object('service_name', s.name, 'equipment_id', m.equipment_id, 'qty', m.qty))
      from public.menu_equipment m
      join public.services s on s.id = m.service_id
      where m.user_id = l.user_id
    ), '[]'::jsonb),
    'items', coalesce((
      select jsonb_agg(to_jsonb(i) - 'user_id')
      from public.event_load_items i
      where i.customer_id = any(v_ids)
    ), '[]'::jsonb),
    'trucks', coalesce((
      select jsonb_agg(to_jsonb(t) - 'user_id')
      from public.trucks t
      where t.user_id = l.user_id
    ), '[]'::jsonb),
    'runs', coalesce((
      select jsonb_agg(to_jsonb(r) - 'user_id')
      from public.event_runs r
      where r.customer_id = any(v_ids)
    ), '[]'::jsonb),
    'settings', (
      select to_jsonb(o) - 'user_id'
      from public.ops_settings o
      where o.user_id = l.user_id
    )
  );
end;
$$;

-- Crew taps Leaving / Arrived / Setup done / Done (or undoes it)
create or replace function public.crew_status(
  p_token uuid, p_customer_id bigint, p_step text, p_done boolean, p_by text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  l public.crew_links%rowtype;
  v_by text := left(nullif(btrim(coalesce(p_by, '')), ''), 60);
  v_at timestamptz := case when p_done then now() end;
begin
  l := public.crew_valid_link(p_token);
  perform public.crew_check_event(l, p_customer_id);
  if p_step not in ('departed', 'arrived', 'setup_done', 'finished') then
    raise exception 'Invalid step';
  end if;

  insert into public.event_runs (user_id, customer_id)
  values (l.user_id, p_customer_id)
  on conflict (customer_id) do nothing;

  update public.event_runs
  set departed_at = case when p_step = 'departed' then v_at else departed_at end,
      arrived_at = case when p_step = 'arrived' then v_at else arrived_at end,
      setup_done_at = case when p_step = 'setup_done' then v_at else setup_done_at end,
      finished_at = case when p_step = 'finished' then v_at else finished_at end,
      status_by = v_by,
      updated_at = now()
  where customer_id = p_customer_id;
end;
$$;

revoke all on function public.crew_check_event(public.crew_links, bigint) from public, anon, authenticated;
revoke all on function public.crew_day(uuid) from public;
revoke all on function public.crew_status(uuid, bigint, text, boolean, text) from public;
grant execute on function public.crew_day(uuid) to anon, authenticated;
grant execute on function public.crew_status(uuid, bigint, text, boolean, text) to anon, authenticated;
