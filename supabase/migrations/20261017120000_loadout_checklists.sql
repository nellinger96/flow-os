-- Load-out checklists: the gear a caterer owns, packing rules (every event,
-- per N guests, per menu item), per-event check-offs for loading the truck and
-- packing back up, and day share links so crews can check items off without
-- an account.
--
-- Additive only: new tables and functions. Existing tables and data are not
-- modified.

-- ---------------------------------------------------------------------------
-- 1. Equipment the caterer owns, with an optional automatic packing rule
-- ---------------------------------------------------------------------------
create table if not exists public.equipment (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 120),
  category text not null default 'other' check (length(category) <= 40),
  stock integer check (stock is null or stock >= 0),
  -- manual: only when linked to a menu item or added by hand
  -- every_event: `qty` on every event
  -- per_guests: `qty` for every `guests_per` guests (rounded up)
  rule text not null default 'manual' check (rule in ('manual', 'every_event', 'per_guests')),
  qty numeric(10,2) not null default 1 check (qty > 0),
  guests_per integer check (guests_per is null or guests_per > 0),
  created_at timestamptz not null default now()
);
create index if not exists equipment_user_id_idx on public.equipment (user_id);

alter table public.equipment enable row level security;
drop policy if exists "Owners manage their equipment" on public.equipment;
create policy "Owners manage their equipment" on public.equipment
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- ---------------------------------------------------------------------------
-- 2. Gear each menu item needs (e.g. Carne asada -> 1 cazuela, 1 tongs)
-- ---------------------------------------------------------------------------
create table if not exists public.menu_equipment (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  service_id bigint not null references public.services(id) on delete cascade,
  equipment_id bigint not null references public.equipment(id) on delete cascade,
  qty numeric(10,2) not null default 1 check (qty > 0),
  primary key (service_id, equipment_id)
);
create index if not exists menu_equipment_user_id_idx on public.menu_equipment (user_id);
create index if not exists menu_equipment_equipment_id_idx on public.menu_equipment (equipment_id);

alter table public.menu_equipment enable row level security;
drop policy if exists "Owners manage their menu gear" on public.menu_equipment;
create policy "Owners manage their menu gear" on public.menu_equipment
  for all
  using (auth.uid() = user_id)
  with check (
    auth.uid() = user_id
    and exists (select 1 from public.equipment e where e.id = equipment_id and e.user_id = auth.uid())
    and exists (select 1 from public.services s where s.id = service_id and s.user_id = auth.uid())
  );

-- ---------------------------------------------------------------------------
-- 3. Per-event checklist state. The list itself is computed from the rules
--    above; rows here only hold check-offs, quantity changes, removed items
--    and one-off items added for that event.
--    item_key: 'eq:<equipment id>' | 'sup:<menu supply name>' | 'custom:<uuid>'
-- ---------------------------------------------------------------------------
create table if not exists public.event_load_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  customer_id bigint not null references public.customers(id) on delete cascade,
  item_key text not null check (length(item_key) between 1 and 200),
  label text check (label is null or length(label) <= 120),
  qty numeric(10,2) check (qty is null or qty >= 0),
  removed boolean not null default false,
  loaded_at timestamptz,
  loaded_by text check (loaded_by is null or length(loaded_by) <= 60),
  returned_at timestamptz,
  returned_by text check (returned_by is null or length(returned_by) <= 60),
  created_at timestamptz not null default now(),
  unique (customer_id, item_key)
);
create index if not exists event_load_items_user_id_idx on public.event_load_items (user_id);

alter table public.event_load_items enable row level security;
drop policy if exists "Owners manage their event checklists" on public.event_load_items;
create policy "Owners manage their event checklists" on public.event_load_items
  for all
  using (auth.uid() = user_id)
  with check (
    auth.uid() = user_id
    and exists (select 1 from public.customers c where c.id = customer_id and c.user_id = auth.uid())
  );

-- ---------------------------------------------------------------------------
-- 4. Crew share links: one link per day, no login, expires automatically
-- ---------------------------------------------------------------------------
create table if not exists public.crew_links (
  token uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  day date not null,
  expires_at timestamptz not null,
  revoked_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists crew_links_user_day_idx on public.crew_links (user_id, day);

alter table public.crew_links enable row level security;
drop policy if exists "Owners manage their crew links" on public.crew_links;
create policy "Owners manage their crew links" on public.crew_links
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- ---------------------------------------------------------------------------
-- 5. Crew functions (called by the public /crew/<token> page)
-- ---------------------------------------------------------------------------
create or replace function public.crew_valid_link(p_token uuid)
returns public.crew_links
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  l public.crew_links%rowtype;
begin
  select * into l
  from public.crew_links
  where token = p_token
    and revoked_at is null
    and now() < expires_at;
  if not found then
    raise exception 'This link has expired or was turned off.';
  end if;
  return l;
end;
$$;

-- Booked events on the link's day, with only what the crew needs
-- (no prices, payments, email or contract details)
create or replace function public.crew_day(p_token uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  l public.crew_links%rowtype;
begin
  l := public.crew_valid_link(p_token);
  return jsonb_build_object(
    'day', l.day,
    'business_name', public.business_name_for(l.user_id),
    'events', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', c.id,
        'full_name', c.full_name,
        'phone', c.phone,
        'address', c.address,
        'city', c.city,
        'service_data', (
          select coalesce(jsonb_object_agg(key, value), '{}'::jsonb)
          from jsonb_each(coalesce(c.service_data, '{}'::jsonb))
          where key in (
            'event_date', 'event_time', 'guest_count', 'setup', 'dietary_restrictions',
            'kitchen_notes', 'timeline',
            'menu_entrees', 'menu_sides', 'menu_drinks', 'menu_desserts', 'menu_supplies',
            'selected_menu_items'
          )
        )
      ) order by c.service_data ->> 'event_time')
      from public.customers c
      where c.user_id = l.user_id
        and c.status = 'sold'
        and left(c.service_data ->> 'event_date', 10) = l.day::text
    ), '[]'::jsonb),
    'equipment', coalesce((
      select jsonb_agg(to_jsonb(e) - 'user_id')
      from public.equipment e
      where e.user_id = l.user_id
    ), '[]'::jsonb),
    'menu_links', coalesce((
      select jsonb_agg(jsonb_build_object('service_name', s.name, 'equipment_id', m.equipment_id, 'qty', m.qty))
      from public.menu_equipment m
      join public.services s on s.id = m.service_id
      where m.user_id = l.user_id
    ), '[]'::jsonb),
    'items', coalesce((
      select jsonb_agg(to_jsonb(i) - 'user_id')
      from public.event_load_items i
      join public.customers c on c.id = i.customer_id
      where i.user_id = l.user_id
        and c.status = 'sold'
        and left(c.service_data ->> 'event_date', 10) = l.day::text
    ), '[]'::jsonb)
  );
end;
$$;

-- Makes sure the event belongs to the link's owner and day
create or replace function public.crew_check_event(l public.crew_links, p_customer_id bigint)
returns void
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform 1
  from public.customers c
  where c.id = p_customer_id
    and c.user_id = l.user_id
    and c.status = 'sold'
    and left(c.service_data ->> 'event_date', 10) = l.day::text;
  if not found then
    raise exception 'Event not found';
  end if;
end;
$$;

-- Check or uncheck an item. p_phase: 'load' (into the truck) or 'return' (packed back)
create or replace function public.crew_mark(
  p_token uuid, p_customer_id bigint, p_item_key text, p_phase text, p_done boolean, p_by text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  l public.crew_links%rowtype;
  v_by text := left(nullif(btrim(coalesce(p_by, '')), ''), 60);
begin
  l := public.crew_valid_link(p_token);
  perform public.crew_check_event(l, p_customer_id);
  if p_phase not in ('load', 'return') then
    raise exception 'Invalid step';
  end if;
  if p_item_key is null or length(p_item_key) not between 1 and 200 then
    raise exception 'Invalid item';
  end if;

  insert into public.event_load_items (user_id, customer_id, item_key)
  values (l.user_id, p_customer_id, p_item_key)
  on conflict (customer_id, item_key) do nothing;

  if p_phase = 'load' then
    update public.event_load_items
    set loaded_at = case when p_done then now() end,
        loaded_by = case when p_done then v_by end
    where customer_id = p_customer_id and item_key = p_item_key;
  else
    update public.event_load_items
    set returned_at = case when p_done then now() end,
        returned_by = case when p_done then v_by end
    where customer_id = p_customer_id and item_key = p_item_key;
  end if;
end;
$$;

-- Add a one-off item the list was missing
create or replace function public.crew_add_item(p_token uuid, p_customer_id bigint, p_label text, p_qty numeric)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  l public.crew_links%rowtype;
  v_label text := btrim(coalesce(p_label, ''));
  v_key text := 'custom:' || gen_random_uuid()::text;
begin
  l := public.crew_valid_link(p_token);
  perform public.crew_check_event(l, p_customer_id);
  if length(v_label) not between 1 and 120 then
    raise exception 'Type what the item is.';
  end if;
  if p_qty is not null and (p_qty < 0 or p_qty > 10000) then
    raise exception 'Invalid quantity';
  end if;

  insert into public.event_load_items (user_id, customer_id, item_key, label, qty)
  values (l.user_id, p_customer_id, v_key, v_label, p_qty);
  return v_key;
end;
$$;

revoke all on function public.crew_valid_link(uuid) from public, anon, authenticated;
revoke all on function public.crew_check_event(public.crew_links, bigint) from public, anon, authenticated;
revoke all on function public.crew_day(uuid) from public;
revoke all on function public.crew_mark(uuid, bigint, text, text, boolean, text) from public;
revoke all on function public.crew_add_item(uuid, bigint, text, numeric) from public;
grant execute on function public.crew_day(uuid) to anon, authenticated;
grant execute on function public.crew_mark(uuid, bigint, text, text, boolean, text) to anon, authenticated;
grant execute on function public.crew_add_item(uuid, bigint, text, numeric) to anon, authenticated;
