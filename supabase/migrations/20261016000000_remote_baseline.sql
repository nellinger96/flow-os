CREATE OR REPLACE FUNCTION "public"."get_contract_by_token"("token" "uuid") RETURNS SETOF "public"."customers"
    LANGUAGE "sql" SECURITY DEFINER
    AS $$
  SELECT * FROM public.customers WHERE public_token = token;
$$;


ALTER FUNCTION "public"."get_contract_by_token"("token" "uuid") OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."sign_contract_by_token"("token" "uuid", "new_service_data" "jsonb") RETURNS "void"
    LANGUAGE "sql" SECURITY DEFINER
    AS $$
  UPDATE public.customers 
  SET 
    status = 'sold',
    contract_url = 'SIGNED_DIGITALLY',
    service_data = new_service_data
  WHERE public_token = token;
$$;


ALTER FUNCTION "public"."sign_contract_by_token"("token" "uuid", "new_service_data" "jsonb") OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."sign_contract_by_token"("token" "uuid", "signature_value" "text") RETURNS "void"
    LANGUAGE "sql" SECURITY DEFINER
    AS $$
  -- Replace 'contract_url' with whatever column actually stores your signature or signed status!
  UPDATE public.customers 
  SET contract_url = signature_value 
  WHERE public_token = token;
$$;


